  function translate(source, lang = language) {
    const clean = String(source || "").trim();
    if (!clean || lang === "ru") return clean;
    return dictionaries[lang]?.[clean] || translatedCatalogText(clean, lang) || patternTranslate(clean, lang) || clean;
  }

  function rememberOriginal(node, attribute, value) {
    const key = attribute ? `i18nOriginal${attribute.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase())}` : "i18nOriginalText";
    if (!(key in node.dataset)) node.dataset[key] = value;
    return node.dataset[key];
  }

  function translateElement(element) {
    if (!(element instanceof Element) || element.closest(".language-switcher")) return;
    ["placeholder", "title", "aria-label"].forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      const original = rememberOriginal(element, attribute, element.getAttribute(attribute) || "");
      element.setAttribute(attribute, translate(original));
    });
  }

  function translateTextNode(node) {
    if (node.parentElement?.closest(".language-switcher, script, style, noscript")) return;
    const raw = node.nodeValue || "";
    const source = raw.trim();
    if (!source) return;
    if (!node.__liberterraOriginalText) node.__liberterraOriginalText = source;
    const original = node.__liberterraOriginalText;
    const next = language === "ru" ? original : translate(original);
    node.nodeValue = raw.replace(source, next);
  }

  function apply(root = document.body) {
    if (!root || applying) return;
    applying = true;
    try {
      document.documentElement.lang = HTML_LANG[language];
      document.documentElement.dataset.language = language;
      if (!document.documentElement.dataset.i18nOriginalTitle) document.documentElement.dataset.i18nOriginalTitle = document.title;
      document.title = translate(document.documentElement.dataset.i18nOriginalTitle);
      translateElement(root instanceof Element ? root : document.documentElement);
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
      let node = walker.currentNode;
      while (node) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        else translateElement(node);
        node = walker.nextNode();
      }
      document.querySelectorAll(".language-switcher button").forEach((button) => {
        const active = button.dataset.language === language;
        button.classList.toggle("is-active", active);
        button.setAttribute("aria-pressed", String(active));
      });
    } finally { applying = false; }
  }

  function setLanguage(next) {
    if (document.body.classList.contains('agent-crm-page')) return;
    if (!SUPPORTED.has(next) || next === language) return;
    language = next;
    try { localStorage.setItem(STORAGE_KEY, next); } catch (_) {}
    apply(document.body);
    window.dispatchEvent(new CustomEvent("liberterra:languagechange", { detail: { language } }));
    try { window.parent?.postMessage({ type: "liberterra-language", language }, location.origin); } catch (_) {}
  }

  function createSwitcher() {
    if (document.body.classList.contains('agent-crm-page')) return;
    if (document.querySelector(".language-switcher")) return;
    const switcher = document.createElement("div");
    switcher.className = "language-switcher";
    switcher.setAttribute("role", "group");
    switcher.setAttribute("aria-label", language === "zh" ? "选择语言" : language === "en" ? "Select language" : "Выбор языка");
    switcher.innerHTML = [
      ["ru", "RU", "Русский"], ["ky", "KG", "Кыргызча"], ["en", "EN", "English"], ["zh", "中文", "中文"],
    ].map(([code, label, title]) => `<button type="button" data-language="${code}" title="${title}" aria-pressed="false">${label}</button>`).join("");
    switcher.addEventListener("click", (event) => {
      const button = event.target.closest("button[data-language]");
      if (button) setLanguage(button.dataset.language);
    });
    const header = document.querySelector(".header-utility-controls, .site-header .header-inner, .crm-header .crm-header-inner, .submission-page-nav");
    if (header) header.append(switcher);
    else document.body.prepend(switcher);
  }

  function boot() {
    createSwitcher();
    apply(document.body);
    const observer = new MutationObserver((mutations) => {
      if (applying) return;
      mutations.forEach((mutation) => mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        else if (node instanceof Element) apply(node);
      }));
    });
    observer.observe(document.body, { childList: true, subtree: true });
    window.addEventListener("storage", (event) => {
      if (document.body.classList.contains('agent-crm-page')) return;
      if (event.key === STORAGE_KEY && SUPPORTED.has(event.newValue)) { language = event.newValue; apply(document.body); }
    });
    window.addEventListener("message", (event) => {
      if (event.origin === location.origin && event.data?.type === "liberterra-language" && SUPPORTED.has(event.data.language)) setLanguage(event.data.language);
    });
  }

  window.LiberterraI18n = { t: translate, apply, setLanguage, get language() { return language; } };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot, { once: true });
  else boot();
